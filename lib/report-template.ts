import type { ExportReadyReport, ExportReadyReportSection } from "@/lib/analysis-hardening";
import { vorqaReportBranding, type ReportBranding } from "@/lib/report-branding";
import { getReportDirection, normalizeReportExportOptions, type ReportDirection, type ReportEvidenceReference, type ReportExportContext, type ReportExportOptions, type ReportLanguage } from "@/types/report-export";

export type ProfessionalReportMetadata = Readonly<{
  projectName?: string;
  projectId?: string;
  client?: string;
  organization?: string;
  analysisType?: string;
  analysisVersion?: number;
  healthScore?: string;
  confidenceScore?: number;
  generatedAt?: string;
  generatedBy?: string;
  workflowStage?: string;
}>;

export type ProfessionalReportSection = ExportReadyReportSection;

export type ProfessionalReportLabels = Readonly<Record<
  "project" | "projectId" | "client" | "organization" | "generated" | "generatedBy" | "analysisType" |
  "version" | "workflowStage" | "health" | "confidence" | "summary" | "findings" | "recommendations" |
  "risks" | "evidence" | "missingInformation" | "timeline" | "readiness" | "warnings" | "page" | "of",
  string
>>;

export type ProfessionalReport = Readonly<{
  title: string;
  language: ReportLanguage;
  direction: ReportDirection;
  labels: ProfessionalReportLabels;
  options: ReportExportOptions;
  metadata: ProfessionalReportMetadata;
  summary: readonly string[];
  findings: readonly string[];
  recommendations: readonly string[];
  risks: readonly string[];
  evidenceReferences: readonly ReportEvidenceReference[];
  missingInformation: readonly string[];
  timeline: NonNullable<ReportExportContext["timeline"]>;
  readiness?: ReportExportContext["readiness"];
  sections: readonly ProfessionalReportSection[];
  warnings: readonly string[];
  branding: ReportBranding;
}>;

